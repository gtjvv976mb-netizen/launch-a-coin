// the carved Config / Card fields, TierParams / ConfigExtParams, 5 events, errors 6037..6045, `issue_tickets` /
// `revoke_ticket` signer renamed `authority` with a writable Config in `issue_tickets`, an optional `price_feed` in
// `initialize`); test/mintdex.test.ts reports any drift between the two. Known difference: the real IDL carries no
// fixed `address` for the sweep constants (they are checked inside `sweep()`), so the builders always pass them.
// Discriminators follow Anchor's rule (sha256("global:<ix>") etc.), so they match the real program when
// the names match. Spec gaps are resolved in favour of safety and recorded in card-program-v2 §18.
