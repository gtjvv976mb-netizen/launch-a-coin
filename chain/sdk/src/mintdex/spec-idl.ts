const f = (name: string, type: IdlType): IdlField => ({ name, type });
const ix = (name: string, accounts: IdlInstructionAccount[], args: IdlField[] = [], docs?: string): IdlInstruction => ({
  name,
  discriminator: anchorDiscriminator("global", name),
  accounts: [...accounts, ...EVENT_CPI],
  args,
  ...(docs ? { docs: [docs] } : {}),
});
const struct = (name: string, fields: IdlField[]): IdlTypeDef => ({ name, type: { kind: "struct", fields } });
const defined = (name: string): IdlType => ({ defined: { name } });

