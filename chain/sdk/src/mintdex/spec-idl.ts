// FeesBelowFloor appended; §18.17: register_card_metaplex, 6036 MetaplexAccountMismatch; mainnet fix pack,
// refs/mainnet/fix-plan.md §2.2 / card-program-v2 §18.18: 27 instructions (observe, set_observers, update_tier_config,
