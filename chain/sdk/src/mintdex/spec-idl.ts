const acc = (name: string, flags = "", extra: Partial<IdlInstructionAccount> = {}): IdlInstructionAccount => ({
  name,
  ...(flags.includes("w") ? { writable: true } : {}),
  ...(flags.includes("s") ? { signer: true } : {}),
  ...(flags.includes("o") ? { optional: true } : {}),
  ...extra,
});
const fixed = (name: string, address: string) => acc(name, "", { address });

