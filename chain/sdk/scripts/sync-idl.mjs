// IDL drop-in: copies the program v2 IDL produced by `anchor build` into the SDK.
//   node scripts/sync-idl.mjs [path/to/mintdex.json]      (default: ../target/idl/mintdex.json)
// Writes idl/mintdex.json (the M1 exit artifact) and src/mintdex/idl.generated.ts, which makes every MintDex
// builder, decoder and the verifier use the real IDL instead of the placeholder in src/mintdex/spec-idl.ts.
// Then run `npm test`: test/mintdex.test.ts lists any drift between the builders and the real account lists.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SDK = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PROGRAM_ID = "4HTSBYfgm5os2kBwFVBv5cd4mPetNmS32Cb4r3YViDon";
const src = resolve(process.argv[2] ?? join(SDK, "..", "target", "idl", "mintdex.json"));
const idl = JSON.parse(readFileSync(src, "utf8"));

const problems = [];
if (idl.address !== PROGRAM_ID) problems.push(`address ${idl.address} != ${PROGRAM_ID}`);
if (!idl.metadata?.spec) problems.push("not an Anchor 0.30+ IDL (metadata.spec missing)");
if (!Array.isArray(idl.instructions) || !idl.instructions.some((i) => i.name === "register_card")) {
  problems.push("no register_card instruction: this is not the v2 card program (the v1 IDL lives at the same path)");
}
for (const ix of idl.instructions ?? []) {
  if (!Array.isArray(ix.discriminator) || ix.discriminator.length !== 8) problems.push(`${ix.name}: bad discriminator`);
}
if (problems.length) {
  console.error(`refusing to sync ${src}:\n  - ${problems.join("\n  - ")}`);
  process.exit(1);
}

mkdirSync(join(SDK, "idl"), { recursive: true });
writeFileSync(join(SDK, "idl", "mintdex.json"), JSON.stringify(idl, null, 2) + "\n");
const ts = `// GENERATED by scripts/sync-idl.mjs from idl/mintdex.json (the \`anchor build\` IDL of program v2).
// null = the program has not been built yet; the SDK then uses the placeholder in spec-idl.ts.
import type { Idl } from "../idl.ts";

export const MINTDEX_IDL_GENERATED: Idl | null = JSON.parse(${JSON.stringify(JSON.stringify(idl))}) as Idl;
`;
writeFileSync(join(SDK, "src", "mintdex", "idl.generated.ts"), ts);
console.log(
  `synced ${idl.instructions.length} instructions, ${(idl.accounts ?? []).length} accounts, ${
    (idl.events ?? []).length
  } events from ${src}`
);
