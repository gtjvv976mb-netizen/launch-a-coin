type Frame = {width: number; height: number; delay: number; minimum: number; compressed: Uint8Array; palette: number[][]};
function readGif(bytes: Uint8Array) {
  let cursor = 6;
  const word = () => {const value = bytes[cursor] | bytes[cursor + 1] << 8; cursor += 2; return value;};
  const width = word(), height = word(), packed = bytes[cursor++]; cursor += 2;
  const table = (size: number) => Array.from({length: size}, () => [bytes[cursor++], bytes[cursor++], bytes[cursor++]]);
  const globalPalette = packed & 128 ? table(1 << ((packed & 7) + 1)) : [];
  const blocks = () => {const output: number[] = []; let size: number; while ((size = bytes[cursor++])) {for (let i = 0; i < size; i++) output.push(bytes[cursor++]);} return Uint8Array.from(output);};
  const frames: Frame[] = [];
  let delay = 0, loops: number | undefined;
  while (cursor < bytes.length) {
    const marker = bytes[cursor++];
    if (marker === 0x3b) break;
    if (marker === 0x21) {
      const label = bytes[cursor++];
      if (label === 0xf9) {const length = bytes[cursor++]; cursor++; delay = word() * 10; cursor += length - 3; expect(bytes[cursor++]).toBe(0);}
      else {const payload = blocks(); if (label === 0xff && new TextDecoder().decode(payload.subarray(0, 11)) === "NETSCAPE2.0") loops = payload[12] | payload[13] << 8;}
      continue;
    }
    if (marker !== 0x2c) throw new Error(`Unexpected GIF block ${marker}`);
    expect(word()).toBe(0); expect(word()).toBe(0);
    const frameWidth = word(), frameHeight = word(), options = bytes[cursor++];
    const palette = options & 128 ? table(1 << ((options & 7) + 1)) : globalPalette;
    const minimum = bytes[cursor++], compressed = blocks();
    frames.push({width: frameWidth, height: frameHeight, delay, minimum, compressed, palette});
  }
  expect(cursor).toBe(bytes.length);
  return {width, height, loops, frames};
}

/** Independent LZW reader checks the generated bytes, rather than the encoder's own input. */
function decode(frame: Frame): Uint8Array {
  const clear = 1 << frame.minimum, end = clear + 1;
  let size = frame.minimum + 1, next = end + 1, bit = 0, previous: number[] | undefined;
  let dictionary: number[][] = [];
  const reset = () => {dictionary = Array.from({length: clear}, (_, index) => [index]); size = frame.minimum + 1; next = end + 1; previous = undefined;};
  const pixels = new Uint8Array(frame.width * frame.height); let written = 0;
  reset();
  while (bit + size <= frame.compressed.length * 8) {
    let code = 0;
    for (let shift = 0; shift < size; shift++, bit++) code |= (frame.compressed[bit >> 3] >> (bit & 7) & 1) << shift;
    if (code === clear) {reset(); continue;}
    if (code === end) break;
    const entry = dictionary[code] ?? (code === next && previous ? [...previous, previous[0]] : undefined);
    if (!entry || written + entry.length > pixels.length) throw new Error("Invalid GIF LZW stream");
    pixels.set(entry, written); written += entry.length;
    if (previous && next < 4096) {
      dictionary[next++] = [...previous, entry[0]];
      if (next === 1 << size && size < 12) size++;
    }
    previous = entry;
  }
  expect(written).toBe(pixels.length);
  return pixels;
}

function face(left: number[], right: number[]): TokenCardPixels {
  const width = 63, height = 88, pixels = new Uint8Array(width * height * 4);
  for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) pixels.set([...(x < width / 2 ? left : right), 255], (y * width + x) * 4);
  return {pixels, width, height};
}
const red = [220, 40, 35], green = [40, 190, 65], blue = [35, 80, 225], yellow = [245, 200, 40];
const front = face(red, green), back = face(blue, yellow);
let bytes: Uint8Array, parsed: ReturnType<typeof readGif>, elapsed: number;

describe("permanent full-card token turntable", () => {
  beforeAll(() => {
    const start = performance.now(); bytes = encodeTokenTurntable(front, back); elapsed = performance.now() - start;
    parsed = readGif(bytes);
  }, 30_000);
  test("encodes an infinite, complete 360-degree loop with readable-face holds", () => {
    expect(TOKEN_ANIMATION_FORMAT).toBe("launchacard-turntable-gif-v1");
    expect(new TextDecoder().decode(bytes.subarray(0, 6))).toBe("GIF89a");
    expect(parsed.width).toBe(TOKEN_ANIMATION_SIZE); expect(parsed.height).toBe(TOKEN_ANIMATION_SIZE);
    expect(parsed.frames).toHaveLength(TOKEN_ANIMATION_FRAMES); expect(parsed.loops).toBe(0);
    for (let index = 0; index < parsed.frames.length; index++) {
      expect(parsed.frames[index].width).toBe(TOKEN_ANIMATION_SIZE);
      expect(parsed.frames[index].height).toBe(TOKEN_ANIMATION_SIZE);
      expect(parsed.frames[index].delay).toBe(index === 0 || index === TOKEN_ANIMATION_FRAMES / 2 ? TOKEN_ANIMATION_HOLD_MS : TOKEN_ANIMATION_FRAME_MS);
    }
    expect(bytes.length).toBeLessThan(TOKEN_ANIMATION_MAX_BYTES);
    console.info(`Token GIF fixture: ${bytes.length} bytes, ${Math.round(elapsed)} ms`);
  });
  test("decodes the actual front and back colors in their correct, unmirrored order", () => {
    for (const [index, left, right] of [[0, red, green], [32, blue, yellow]] as const) {
      const frame = parsed.frames[index], pixels = decode(frame);
      const color = (x: number, y: number) => frame.palette[pixels[y * TOKEN_ANIMATION_SIZE + x]];
      expect(color(390, 512)).toEqual(left); expect(color(634, 512)).toEqual(right);
      expect(color(0, 0)).toEqual([...TOKEN_ANIMATION_BACKGROUND]);
      expect(color(512, 100)).toEqual([...TOKEN_ANIMATION_BACKGROUND]);
      expect(color(236, 125)).toEqual([...TOKEN_ANIMATION_BACKGROUND]);
    }
  });
  test("the two side views retain a thin neutral-gold card edge", () => {
    for (const index of [16, 48]) {
      const frame = parsed.frames[index], pixels = decode(frame);
      expect(frame.palette[pixels[512 * TOKEN_ANIMATION_SIZE + 512]]).toEqual([222, 204, 158]);
      expect(frame.palette[pixels[512 * TOKEN_ANIMATION_SIZE + 508]]).toEqual([...TOKEN_ANIMATION_BACKGROUND]);
    }
  });
  test("every projected corner stays inside both the square and a circular token avatar", () => {
    for (let index = 0; index < 720; index++) {
      for (const [x, y] of tokenTurntableCorners(index / 720 * Math.PI * 2)) {
        expect(x).toBeGreaterThan(0); expect(x).toBeLessThan(TOKEN_ANIMATION_SIZE);
        expect(y).toBeGreaterThan(0); expect(y).toBeLessThan(TOKEN_ANIMATION_SIZE);
        expect(Math.hypot(x - 512, y - 512)).toBeLessThan(502);
      }
    }
  });
  test("invalid pixels and non-card aspect ratios fail before encoding", () => {
    for (const bad of [{...front, width: 0}, {...front, height: 2049}, {...front, pixels: front.pixels.subarray(4)}, {...front, width: 88, height: 63}]) {
      expect(() => encodeTokenTurntable(bad, back)).toThrow("canonical 63:88");
    }
  });
  test("indexing first, then encoding, gives the same bytes, and the output buffer never grows", () => {
    const faces = indexTokenFaces(front, back);
    expect(faces.front.pixels).toHaveLength(front.width * front.height);
    const split = encodeIndexedTurntable(faces);
    expect(split).toEqual(bytes);
    // A view of the one buffer sized at the limit: no growth copy while encoding.
    expect(split.buffer.byteLength).toBe(TOKEN_ANIMATION_MAX_BYTES);
  });
  test("offset input views keep their own pixels and are never modified", () => {
    const storage = new Uint8Array(front.pixels.length + 8); storage.fill(99); storage.set(front.pixels, 4);
    const view = {...front, pixels: storage.subarray(4, -4)};
    expect(encodeTokenTurntable(view, back)).toEqual(bytes);
    expect(() => encodeTokenTurntable({...view, pixels: view.pixels.subarray(1)}, back)).toThrow();
    expect(storage[0]).toBe(99); expect(storage[storage.length - 1]).toBe(99);
    expect(view.pixels).toEqual(front.pixels);
  });
});

describe("one card render at a time per isolate", () => {
  test("jobs never overlap, keep their results, and a failed job frees the slot", async () => {
    const slot = createRendererSlot({pollMs: 1});
    let running = 0, most = 0;
    const job = (value: number, fail = false) => slot(async () => {
      running++; most = Math.max(most, running);
      await new Promise(resolve => setTimeout(resolve, 5));
      running--;
      if (fail) throw new Error("render failed");
      return value;
    });
    const results = await Promise.allSettled([job(1), job(2, true), job(3), job(4)]);
    expect(most).toBe(1);
    expect(results.map(result => result.status === "fulfilled" ? result.value : (result.reason as Error).message)).toEqual([1, "render failed", 3, 4]);
  });
  test("a holder that never settles stops blocking once its lease ends", async () => {
    const slot = createRendererSlot({leaseMs: 30, pollMs: 1});
    void slot(() => new Promise(() => {}));
    const started = Date.now();
    expect(await slot(async () => "next")).toBe("next");
    expect(Date.now() - started).toBeGreaterThanOrEqual(25);
  });
  test("a waiter gives up with a retryable message instead of waiting forever", async () => {
    const slot = createRendererSlot({leaseMs: 1_000, waitMs: 20, pollMs: 1});
    void slot(() => new Promise(() => {}));
    await expect(slot(async () => "never")).rejects.toThrow("Try again in a moment");
  });
});
